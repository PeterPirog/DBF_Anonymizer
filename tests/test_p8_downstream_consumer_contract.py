CONSUMER_PRODUCER_ID = "downstream-consumer-simulation"


class FrozenDownstreamConsumer:
    """The simulated transport-neutral downstream host adapter.

    The host exposes pseudonymization and verification while INDEPENDENTLY
    disabling recovery: the adapter's immutable local policy is
    ``RecoveryPolicy.DISABLED`` and its ``recover`` delegation can only ever
    produce the typed policy refusal.  Everything is called through the
    public package root; the host knows no private module and no transport
    framework.
    """

    def __init__(self) -> None:
        self._recovery_policy = public.RecoveryPolicy.DISABLED

    def capabilities(self) -> public.Capabilities:
        return public.capabilities(self._recovery_policy)

    def build_plan(
        self,
        source: Path,
        output: Path,
        vault: Path,
        *,
        relationship_document: dict[str, Any] | None = None,
    ) -> public.Plan:
        return public.build_plan(
            source,
            output,
            vault,
            relationship_document=relationship_document,
        )

    def pseudonymize(self, plan: public.Plan, *, workers: int = 1) -> public.PseudonymizationResult:
        return public.pseudonymize(plan, workers=workers)

    def verify_dataset(
        self,
        result: public.PseudonymizationResult,
        *,
        source: Path,
        vault: Path,
    ) -> public.VerificationResult:
        return public.verify_dataset(result, source=source, vault=vault)

    def create_transfer_bundle(
        self,
        result: public.PseudonymizationResult,
        *,
        destination: Path,
        profile: str,
    ) -> public.TransferBundleResult:
        return public.create_transfer_bundle(result, destination=destination, profile=profile)

    def verify_transfer_bundle(self, bundle: Path) -> public.TransferBundleResult:
        return public.verify_transfer_bundle(bundle)

    def recover(self, pseudonymized: Path, *, vault: Path, output: Path) -> public.RecoveryResult:
        return public.recover(
            pseudonymized,
            vault=vault,
            output=output,
            recovery_policy=self._recovery_policy,
        )


