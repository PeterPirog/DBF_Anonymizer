def test_downstream_consumer_refuses_before_vault_access_without_any_vault(
    tmp_path: Path,
) -> None:
    """The disabled consumer-facing recovery refusal precedes ALL validation
    and access: with a MISSING vault and a MISSING pseudonymized dataset the
    typed refusal is still exactly POLICY_DISABLED (never a path error), no
    SQLite connection is attempted and nothing is created."""
    consumer = FrozenDownstreamConsumer()
    calls: Counter[str] = Counter()

    def forbidden_sqlite(*args: object, **kwargs: object) -> Any:
        calls["sqlite_connect"] += 1
        raise AssertionError("disabled recovery opened SQLite")

    output = tmp_path / "recovered"
    with pytest.MonkeyPatch.context() as patch:
        patch.setattr(sqlite3, "connect", forbidden_sqlite)
        with pytest.raises(public.RecoveryError) as caught:
            consumer.recover(
                tmp_path / "missing-pseudonymized",
                vault=tmp_path / "missing-private-vault.sqlite",
                output=output,
            )
    assert calls == Counter()
    assert caught.value.code is public.ErrorCode.RECOVERY_NOT_PERMITTED
    assert caught.value.context.detail_code == "POLICY_DISABLED"
    assert not output.exists()
