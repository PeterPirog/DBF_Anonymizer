def _code_column(root: Path, relative: str) -> tuple[tuple[int, bool, object], ...]:
    """The per-record (physical_index, deleted, CODE) column through public reads."""
    return tuple(
        (record.physical_index, record.deleted, record.values.get("CODE"))
        for record in dbfbridge.iter_records(  # type: ignore[attr-defined]
            root / relative, include_deleted=True, memo="inline"
        )
    )


def _assert_pk_fk_preserved(source: Path, output: Path) -> None:
    """Objective declared PK/FK preservation through public reads only.

    The declared relation is north/data.dbf CODE (PRIMARY) ->
    south/data.dbf CODE (FOREIGN).  The evidence is per-value, not row
    counts: the FK join stays valid, distinct originals stay bijective and
    every transformed member value is a genuine pseudonym.
    """
    parent_before = _code_column(source, "north/data.dbf")
    child_before = _code_column(source, "south/data.dbf")
    parent_after = _code_column(output, "north/data.dbf")
    child_after = _code_column(output, "south/data.dbf")

    assert [row[0] for row in parent_before] == [row[0] for row in parent_after]
    assert [row[1] for row in parent_before] == [row[1] for row in parent_after]
    assert [row[1] for row in child_before] == [row[1] for row in child_after]

    parent_by_index = {row[0]: row for row in parent_after}
    child_by_index = {row[0]: row for row in child_after}

    parent_originals = {row[2]: row[0] for row in parent_before if row[2]}
    assert len(parent_originals) == 2
    pseudonym_by_original = {}
    for original, index in parent_originals.items():
        pseudonym = parent_by_index[index][2]
        assert pseudonym != original
        assert isinstance(pseudonym, str) and pseudonym.strip() != ""
        pseudonym_by_original[original] = pseudonym
    assert len(set(pseudonym_by_original.values())) == len(pseudonym_by_original)

    join_before = [row[2] for row in child_before if row[2]]
    assert join_before == ["PARENT-1"]
    child_joined = [row for row in child_after if row[2]]
    assert len(child_joined) == 1
    assert child_joined[0][2] == pseudonym_by_original["PARENT-1"]

    assert parent_by_index[0][1] is False
    assert parent_by_index[1][1] is True
    assert child_by_index[0][1] is True
    assert child_by_index[1][1] is False
    assert child_by_index[1][2] is None


def _assert_clean_data_only_bundle(
    bundle: Path, frozen: dict[str, Any], consumer_result: public.TransferBundleResult
) -> tuple[list[str], bool]:
    """The bundle content scan under the FROZEN 1.0 transfer-bundle contract."""
    contract = frozen["transfer_bundle"]
    files = [
        path.relative_to(bundle).as_posix() for path in sorted(bundle.rglob("*")) if path.is_file()
    ]
    manifest_filename = str(contract["manifest_filename"])
    allowed_suffixes = {"." + str(item).lower() for item in contract["allowed_artifact_classes"]}
    allowlist_ok = all(
        name == manifest_filename or Path(name).suffix.lower() in allowed_suffixes for name in files
    )
    forbidden_suffixes = {str(item) for item in contract["forbidden_suffixes"]}
    forbidden_markers = {str(item) for item in contract["forbidden_basename_markers"]}
    forbidden_absent = not any(
        Path(name).suffix in forbidden_suffixes
        or any(marker in name.lower() for marker in forbidden_markers)
        for name in files
    )
    canaries_absent = not any(
        canary.encode("utf-8") in path.read_bytes()
        for path in bundle.rglob("*")
        if path.is_file()
        for canary in TEXT_CANARIES
    ) and not any(
        canary in path.read_bytes()
        for path in bundle.rglob("*")
        if path.is_file()
        for canary in BINARY_CANARIES
    )
    assert allowlist_ok is True
    assert forbidden_absent is True
    assert canaries_absent is True
    assert consumer_result.profile is public.TransferProfile.DATA_ONLY
    assert consumer_result.verified is True
    assert files
    assert any(name.endswith(".dbf") for name in files)
    assert any(name.endswith(".fpt") for name in files)
    return files, canaries_absent


def test_downstream_consumer_capabilities_with_recovery_independently_disabled() -> None:
    """The host discovers its consumer-facing capability set with recovery
    disabled by ITS OWN policy: pseudonymization, verification and the
    transfer bundle remain available while recovery is refused."""
    consumer = FrozenDownstreamConsumer()
