"""REQ-P8-003: frozen downstream-consumer acceptance contract.

ONE frozen acceptance test suite that simulates exactly what the downstream
host (``mcp-vfp9sp2-toolchain``) needs, WITHOUT importing, checking out or
otherwise depending on that host:

1. capability discovery through PUBLIC imports with recovery INDEPENDENTLY
   disabled by host policy (``RecoveryPolicy.DISABLED``);
2. pseudonymization and verification invoked through PUBLIC Python imports
   only (``import dbf_anonymizer`` — the package root, never a private
   ``dbf_anonymizer.*`` submodule);
3. an INJECTED, producer-independent external relationship/index metadata
   document (REQ-P6-006 contract) accepted through the PUBLIC planning
   boundary: explicit provenance, authority, assurance, normalized relative
   identities and at least one index claim with an explicit verification
   state;
4. a SYNTHETIC MULTI-TABLE dataset (the canonical REQ-P8-002 three-table
   fixture) with a declared PK/FK relation;
5. preserved declared PK/FK relations (truthful verification assurance and
   per-value join/bijection evidence through public reads — never inferred
   from row counts);
6. a CLEAN transferable DATA_ONLY bundle created and INDEPENDENTLY verified
   (source absent), with the forbidden recovery/secret/index material absent
   under the frozen 1.0 transfer-bundle contract.

The consumer requirements are FROZEN against the committed REQ-P8-001
snapshot ``contracts/public-contract-1.0.json``: any incompatible change to
a required consumer capability (root export, callable signature, recovery
policy vocabulary, external-metadata schema/resource/digest/vocabulary,
transfer-bundle surface) fails this suite.  No second snapshot is created
and no snapshot is ever regenerated by a failing test.

The dataset is 100% synthetic (written through the public ``dbfbridge``
writer); no production data, no network access, no MCP/server framework and
no real VFP runtime is involved.
"""

